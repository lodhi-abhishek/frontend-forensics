let decodedMask: Uint8Array | null = null;

function getLogoMask() {
  if (decodedMask) return decodedMask;

  const binary = atob(LOGO_MASK_BASE64);
  decodedMask = Uint8Array.from(binary, (character) => character.charCodeAt(0));
  return decodedMask;
}

export function isLogoCellOccupied(index: number) {
  const mask = getLogoMask();
  return (mask[index >> 3] & (1 << (index & 7))) !== 0;
}
